// Forced-DEBUG control for the output-lint replay repair.
//
// The 12-case replay in docs/v2/evidence/P3.4/output-lint-repair/ runs clean, so
// in that run `if (r.status !== 0)` in tooling-guard.test.mjs never fires and the
// replay says nothing at all about the one DEBUG line the output repair moved.
// This control forces it, then measures exactly what the replay's normalisation
// has to absorb for the two versions of that file to be comparable at all.
//
// Both sides of the comparison:
//   * the "before" file, read out of git at ORIGIN_COMMIT on every run and
//     written under its own repo-relative path, so the file's *name* matches and
//     only its *directory* differs from the working-tree copy;
//   * the current working-tree file;
// each run under the pinned interpreter with `node --test`, against the same
// ignored tool fixture, which is a copy of the read-only build/ir4/ patched so
// that one attempt number fails. Nothing else in the tool's behaviour changes:
// every other invocation is delegated to the real tool, untouched.
//
//   ~/.local/share/apunta-node/node-v24.19.0-linux-x64/bin/node \
//     docs/v2/evidence/output-lint-replay-repair/forced-debug-control.mjs
//
// Exits non-zero if any check fails. Writes only under the ignored
// build/evidence-replay-repair/. Reads git, the committed proof and checker, the
// ignored tool copy, and the stdout/stderr of its own runs. Invokes no app,
// server, model, database, audio input, display, network or install, and never
// contacts port 7717.

import { spawnSync } from 'node:child_process';
import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format } from 'node:util';
import {
  auditOutside,
  firstDifference,
  NORMALISED,
  normalise,
  normalisePathFirst,
  rulesFired,
} from './normalisation.mjs';

const ORIGIN_COMMIT = '3bd142f';
const CASE = 'docs/v2/evidence/P3.4/proposal-ir4/tooling-guard.test.mjs';
const NODE =
  process.env.APUNTA_NODE ??
  join(process.env.HOME ?? '', '.local/share/apunta-node/node-v24.19.0-linux-x64/bin/node');
const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = join(HERE, '../../../..');
const SCRATCH = join(REPO, 'build/evidence-replay-repair');
const TOOL_SRC = join(REPO, 'build/ir4');
const CHECKER = join(REPO, 'docs/v2/evidence/P3.4/output-lint-repair/replay-check.mjs');

let failures = 0;
const say = (...args) => process.stdout.write(format(...args) + '\n');
const check = (id, ok, detail) => {
  if (ok) say(`  ok    ${id.padEnd(46)} ${detail}`);
  else {
    failures += 1;
    say(`  FAIL  ${id.padEnd(46)} ${detail}`);
  }
};

const sha256 = (path) => createHash('sha256').update(readFileSync(path)).digest('hex');

const version = spawnSync(NODE, ['--version'], { encoding: 'utf8' });
if (version.status !== 0 || version.stdout.trim() !== 'v24.19.0') {
  say(`FAIL: pinned interpreter is not v24.19.0 (${NODE}: ${(version.stdout || version.stderr).trim()})`);
  process.exit(1);
}

// ---------------------------------------------------------------------------
// Check 0: the checker this control exists to defend lists the two rules in the
// order it needs. The control carries its own copy of the rules (the checker's
// directory may not gain files), so without this read the two could drift apart
// silently and the control would keep passing on rules the checker no longer
// applies.
{
  const text = readFileSync(CHECKER, 'utf8');
  const lineRule = text.indexOf('/tooling-guard\\.test\\.mjs:\\d+/g');
  const pathRule = text.indexOf('/[^ \\n]*tooling-guard\\.test\\.mjs/g');
  check(
    'C0 checker lists line rule before path rule',
    lineRule !== -1 && pathRule !== -1 && lineRule < pathRule,
    `line rule at char ${lineRule}, path rule at char ${pathRule}`,
  );
}

// ---------------------------------------------------------------------------
// The failing tool fixture: a copy of the read-only ignored tool, with
// build-dispatch.mjs renamed aside and a wrapper in its place that fails on one
// attempt number and delegates everything else to the real tool.
const FORCE_TEMPLATE = (attempt) => `// Generated by docs/v2/evidence/output-lint-replay-repair/.
// An ignored, intentionally failing copy of build/ir4/build-dispatch.mjs.
// Only the invocation the control needs is broken; every other one is the real
// tool, run unmodified.
import { spawnSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const args = process.argv.slice(2);
const i = args.indexOf('--attempt');
if (i >= 0 && args[i + 1] === '${attempt}') {
  process.stderr.write('BROKEN TOOL: forced failure on --attempt ${attempt}\\n');
  process.exit(1);
}
const r = spawnSync(process.execPath, [join(here, 'build-dispatch.real.mjs'), ...args], {
  stdio: 'inherit',
  env: process.env,
});
process.exit(r.status ?? 1);
`;

const failingTool = (name, attempt) => {
  const dir = join(SCRATCH, 'tools', name);
  rmSync(dir, { force: true, recursive: true });
  mkdirSync(dir, { recursive: true });
  for (const entry of readdirSync(TOOL_SRC)) copyFileSync(join(TOOL_SRC, entry), join(dir, entry));
  copyFileSync(join(dir, 'build-dispatch.mjs'), join(dir, 'build-dispatch.real.mjs'));
  rmSync(join(dir, 'build-dispatch.mjs'));
  writeFileSync(join(dir, 'build-dispatch.mjs'), FORCE_TEMPLATE(attempt));
  return dir;
};

// Two fixtures, breaking on different attempt numbers. The second one exists so
// the control can compare runs whose *semantic* output differs and show that the
// normalisation does not flatten them into each other.
const TOOL4 = failingTool('tool-attempt4', '4');
const TOOL1 = failingTool('tool-attempt1', '1');

// ---------------------------------------------------------------------------
// The "before" file, from git, at its own repo-relative path so that only its
// directory differs from the working-tree copy's.
const blob = spawnSync('git', ['show', `${ORIGIN_COMMIT}:${CASE}`], { cwd: REPO, encoding: 'utf8' });
if (blob.status !== 0) {
  say(`FAIL: cannot read ${ORIGIN_COMMIT}:${CASE}`);
  process.exit(1);
}
const ORIGINAL = join(SCRATCH, 'originals', CASE);
mkdirSync(dirname(ORIGINAL), { recursive: true });
writeFileSync(ORIGINAL, blob.stdout);

const CURRENT = join(REPO, CASE);
say(`tool copy    ${TOOL_SRC}/build-dispatch.mjs  sha256 ${sha256(join(TOOL_SRC, 'build-dispatch.mjs'))}`);
say(`before file  ${ORIGIN_COMMIT}:${CASE}  sha256 ${sha256(ORIGINAL)}`);
say(`after file   ${CASE}  sha256 ${sha256(CURRENT)}`);
say('');

const run = (label, scriptPath, toolDir) => {
  const r = spawnSync(NODE, ['--test', scriptPath], {
    cwd: REPO,
    env: {
      ...process.env,
      APUNTA_V2_PLAN_DIR_REAL: join(REPO, 'docs/v2'),
      APUNTA_TOOL_DIR: toolDir,
    },
    encoding: 'utf8',
  });
  const dir = join(SCRATCH, 'runs', label);
  mkdirSync(dir, { recursive: true });
  writeFileSync(join(dir, 'stdout'), r.stdout ?? '');
  writeFileSync(join(dir, 'stderr'), r.stderr ?? '');
  writeFileSync(join(dir, 'status'), `${r.status}\n`);
  return { label, out: r.stdout ?? '', err: r.stderr ?? '', status: r.status };
};

const orig4 = run('orig-attempt4', ORIGINAL, TOOL4);
const new4 = run('new-attempt4', CURRENT, TOOL4);
const orig1 = run('orig-attempt1', ORIGINAL, TOOL1);
const new1 = run('new-attempt1', CURRENT, TOOL1);

const debugLines = (text) => text.split('\n').filter((line) => line.startsWith('DEBUG '));
const marks = (text) => [...text.matchAll(/[✔✖]/gu)].map((m) => m[0]);
const frames = (text) =>
  [...text.matchAll(/(?:file:\/\/\S*?|[^\s(]*?)(tooling-guard\.test\.mjs):(\d+):(\d+)/gu)].map((m) => ({
    tail: m[0],
    line: Number(m[2]),
    column: Number(m[3]),
  }));

// ------------------------------------------------------------------ the pair
say('== forced on --attempt 4 (the case the DEBUG line exists for)');

check(
  'C1 exit status equal on both sides and non-zero',
  orig4.status === new4.status && orig4.status !== 0,
  `before ${orig4.status} / after ${new4.status}`,
);
check(
  'C2 DEBUG lines: same count, byte-identical, none normalised',
  debugLines(orig4.out).length === debugLines(new4.out).length &&
    debugLines(orig4.out).join('\n') === debugLines(new4.out).join('\n') &&
    normalise(debugLines(orig4.out).join('\n')) === debugLines(new4.out).join('\n'),
  `count ${debugLines(orig4.out).length}, bytes identical, DEBUG survives normalisation`,
);
check(
  'C3 raw stdout NOT byte-identical (so C5 is doing work)',
  orig4.out !== new4.out,
  `raw streams differ in ${rulesFired(orig4.out).join(' + ') || 'no permitted shape'}`,
);
check('C3b raw stderr byte-identical', orig4.err === new4.err, `${orig4.err.length} bytes, both sides`);
check(
  'C4 pass/fail marks identical, same count',
  marks(orig4.out).join('') === marks(new4.out).join(''),
  `${marks(orig4.out).filter((m) => m === '✖').length} failing of ${marks(orig4.out).length}`,
);
check(
  'C5 equal after the repaired normalisation order',
  normalise(orig4.out) === normalise(new4.out) && normalise(orig4.err) === normalise(new4.err),
  'stdout and stderr both',
);
check(
  'C6 UNEQUAL under the previously committed order (D1)',
  normalisePathFirst(orig4.out) !== normalisePathFirst(new4.out),
  `first difference ${firstDifference(normalisePathFirst(orig4.out), normalisePathFirst(new4.out))}`,
);
{
  const before = frames(orig4.out);
  const after = frames(new4.out);
  const deltas = before.map((f, i) => (after[i] ? after[i].line - f.line : NaN));
  check(
    'C7 every stack frame shifts by exactly +1',
    before.length > 0 && before.length === after.length && deltas.every((d) => d === 1),
    `${before.length} frames, deltas ${[...new Set(deltas)].join(',')}`,
  );
}
check(
  'C8 nothing normalised outside the three permitted shapes',
  [
    ...auditOutside(NORMALISED, orig4.out),
    ...auditOutside(NORMALISED, new4.out),
    ...auditOutside(NORMALISED, orig4.err),
    ...auditOutside(NORMALISED, new4.err),
  ].length === 0,
  'no substantive line absorbed',
);

// --------------------------------------------------------- second forcing
say('');
say('== forced on --attempt 1 (a different broken invocation, same shift)');

check(
  'C9 exit status equal on both sides and non-zero',
  orig1.status === new1.status && orig1.status !== 0,
  `before ${orig1.status} / after ${new1.status}`,
);
check(
  'C10 equal after the repaired normalisation order',
  normalise(orig1.out) === normalise(new1.out) && normalise(orig1.err) === new1.err,
  'stdout and stderr both',
);
check(
  'C11 UNEQUAL under the previously committed order (D1)',
  normalisePathFirst(orig1.out) !== normalisePathFirst(new1.out),
  `first difference ${firstDifference(normalisePathFirst(orig1.out), normalisePathFirst(new1.out))}`,
);

// ------------------------------------------------------------ negative controls
say('');
say('== negative controls: different semantic output must stay unequal');

const UNEQUAL_PAIRS = [
  ['N1 same file, different broken invocation (after)', new4, new1],
  ['N2 same file, different broken invocation (before)', orig4, orig1],
  ['N3 across the invocations, before against after', orig4, new1],
];
for (const [id, a, b] of UNEQUAL_PAIRS) {
  const differsBoth = normalise(a.out) !== normalise(b.out) && normalisePathFirst(a.out) !== normalisePathFirst(b.out);
  check(
    id,
    differsBoth,
    `repaired order: ${normalise(a.out) === normalise(b.out) ? 'EQUAL (wrong)' : 'unequal'}; ` +
      `previous order: ${normalisePathFirst(a.out) === normalisePathFirst(b.out) ? 'EQUAL (wrong)' : 'unequal'}`,
  );
}
{
  // One substantive character: a passing test reported as failing.
  const mutated = new4.out.replace('✔ extra: attempts 1-3 unchanged', '✖ extra: attempts 1-3 unchanged');
  check(
    'N4 a changed verdict stays unequal under both orders',
    mutated !== new4.out && normalise(mutated) !== normalise(new4.out) && normalisePathFirst(mutated) !== normalisePathFirst(new4.out),
    `one character, ${mutated === new4.out ? 'NOT APPLIED' : 'applied'}`,
  );
  // The audit's own negative control: it passes on the real output, and rejects
  // a rule set that also rewrites digits — the way an over-broad rule would
  // quietly absorb a counterexample verdict.
  check(
    'N5 the audit rejects an over-broad rule set',
    auditOutside(NORMALISED, new4.out).length === 0 && auditOutside([...NORMALISED, [/\b\d+\b/g, '#']], new4.out).length > 0,
    `0 out-of-shape lines with the four rules, ${auditOutside([...NORMALISED, [/\b\d+\b/g, '#']], new4.out).length} with an extra rule rewriting digits`,
  );
  // And the complement: a change confined to a reporter timing is absorbed.
  const timed = new4.out.replace(/(\(\d+(\.\d+)?ms\))/, '(999.999ms)');
  check(
    'N6 a change inside a reporter timing is still absorbed',
    timed !== new4.out && normalise(timed) === normalise(new4.out),
    'rule 1 is live, and confined',
  );
}

say('');
say(`${failures === 0 ? 'PASS' : 'FAIL'}: ${failures} failed check(s); runs under ${SCRATCH}/runs/.`);
process.exit(failures === 0 ? 0 : 1);